-- H2 schema (PostgreSQL-compatible types). Amounts are BIGINT minor units (paise).

CREATE TABLE IF NOT EXISTS payments (
  id                VARCHAR(64)  PRIMARY KEY,
  merchant_id       VARCHAR(64)  NOT NULL,
  merchant_order_id VARCHAR(128) NOT NULL,
  amount            BIGINT       NOT NULL CHECK (amount > 0),
  currency          CHAR(3)      NOT NULL,
  payment_token     VARCHAR(128) NOT NULL,
  capture_requested BOOLEAN      NOT NULL,
  status            VARCHAR(32)  NOT NULL,
  psp               VARCHAR(32),
  psp_reference     VARCHAR(128),
  failure_code      VARCHAR(64),
  version           INT          NOT NULL DEFAULT 0,
  created_at        TIMESTAMP    NOT NULL,
  updated_at        TIMESTAMP    NOT NULL,
  CONSTRAINT uq_merchant_order UNIQUE (merchant_id, merchant_order_id),
  CONSTRAINT uq_psp_ref        UNIQUE (psp, psp_reference)
);
CREATE INDEX IF NOT EXISTS idx_payments_status_updated ON payments (status, updated_at);

CREATE TABLE IF NOT EXISTS idempotency_keys (
  merchant_id   VARCHAR(64)   NOT NULL,
  idem_key      VARCHAR(128)  NOT NULL,
  request_hash  VARCHAR(64)   NOT NULL,
  status        VARCHAR(16)   NOT NULL,
  response_code INT,
  response_body VARCHAR(4000),
  payment_id    VARCHAR(64),
  created_at    TIMESTAMP     NOT NULL,
  PRIMARY KEY (merchant_id, idem_key)
);
CREATE INDEX IF NOT EXISTS idx_idem_payment ON idempotency_keys (payment_id);

CREATE TABLE IF NOT EXISTS payment_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id  VARCHAR(64) NOT NULL,
  from_status VARCHAR(32),
  to_status   VARCHAR(32) NOT NULL,
  actor       VARCHAR(32) NOT NULL,
  metadata    VARCHAR(2000),
  created_at  TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS refunds (
  id              VARCHAR(64) PRIMARY KEY,
  payment_id      VARCHAR(64) NOT NULL REFERENCES payments(id),
  amount          BIGINT      NOT NULL CHECK (amount > 0),
  status          VARCHAR(16) NOT NULL,
  psp_reference   VARCHAR(128),
  idempotency_key VARCHAR(128) NOT NULL,
  created_at      TIMESTAMP   NOT NULL,
  CONSTRAINT uq_refund_idem UNIQUE (payment_id, idempotency_key)
);

CREATE TABLE IF NOT EXISTS accounts (
  id       VARCHAR(128) PRIMARY KEY,
  type     VARCHAR(16)  NOT NULL,
  currency CHAR(3)      NOT NULL
);

CREATE TABLE IF NOT EXISTS ledger_transactions (
  id         VARCHAR(128) PRIMARY KEY,
  payment_id VARCHAR(64),
  kind       VARCHAR(16)  NOT NULL,
  created_at TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS ledger_entries (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  txn_id     VARCHAR(128) NOT NULL REFERENCES ledger_transactions(id),
  account_id VARCHAR(128) NOT NULL REFERENCES accounts(id),
  direction  CHAR(1)      NOT NULL CHECK (direction IN ('D','C')),
  amount     BIGINT       NOT NULL CHECK (amount > 0),
  currency   CHAR(3)      NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_account ON ledger_entries (account_id);
CREATE INDEX IF NOT EXISTS idx_ledger_txn ON ledger_entries (txn_id);

CREATE TABLE IF NOT EXISTS outbox (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic      VARCHAR(64)   NOT NULL,
  msg_key    VARCHAR(128)  NOT NULL,
  payload    VARCHAR(4000) NOT NULL,
  published  BOOLEAN       NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP     NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outbox_unpublished ON outbox (published, id);

CREATE TABLE IF NOT EXISTS webhook_inbox (
  psp         VARCHAR(32)   NOT NULL,
  event_id    VARCHAR(128)  NOT NULL,
  payload     VARCHAR(4000),
  received_at TIMESTAMP     NOT NULL,
  PRIMARY KEY (psp, event_id)
);
